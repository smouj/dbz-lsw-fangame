import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';

const ROOT = process.cwd();
const SOURCE = join(ROOT, 'docs/rom/research-v4-fx/external/DBZ_LSW_ROM_RESEARCH_V4_FX/data/beam_actor_screen_offsets_v4.json');
const OUT = join(ROOT, 'src/data/generated/romBeamSequenceSelectors.generated.ts');

interface RawRow {
  cardId: number | string;
  cardName: string;
  handler: string;
  animationResource: string;
  actorRecordId: number | string;
  visualProfileKey: string;
  sequence: string;
  evidence: string;
}

function parseHex(value: string): number {
  return Number.parseInt(value.replace(/^0x/i, ''), 16);
}

const rows = (JSON.parse(readFileSync(SOURCE, 'utf8')) as RawRow[])
  .map(row => ({
    cardId: Number(row.cardId),
    cardName: row.cardName,
    handler: parseHex(row.handler),
    animationResource: parseHex(row.animationResource),
    actorRecordId: Number(row.actorRecordId),
    actorVisualProfileKey: parseHex(row.visualProfileKey),
    sequence: parseHex(row.sequence),
    evidence: row.evidence,
  }))
  .sort((a, b) =>
    a.cardId - b.cardId ||
    a.actorVisualProfileKey - b.actorVisualProfileKey ||
    a.animationResource - b.animationResource);

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, [
  '// Auto-generated by scripts/generate-rom-beam-sequence-selectors.ts',
  '// Source: docs/rom/research-v4-fx/.../beam_actor_screen_offsets_v4.json',
  '// Do not edit by hand.',
  `export const ROM_BEAM_SEQUENCE_SELECTORS = ${JSON.stringify(rows, null, 2)} as const;`,
  '',
].join('\n'));

console.log(`Generated ${rows.length} ROM beam sequence selector rows -> ${OUT}`);
